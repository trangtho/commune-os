-- Citizen AI chat history is private to the authenticated citizen + tenant.
-- Keep this schema separate from the public RAG knowledge index.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS citizen_ai_conversations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  citizen_id uuid NOT NULL REFERENCES citizens(id) ON DELETE CASCADE,
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id, citizen_id, tenant_id)
);
CREATE INDEX IF NOT EXISTS citizen_ai_conversations_owner_idx
  ON citizen_ai_conversations (citizen_id, tenant_id, updated_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS citizen_ai_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id uuid NOT NULL,
  citizen_id uuid NOT NULL,
  tenant_id uuid NOT NULL,
  role text NOT NULL CHECK (role IN ('citizen', 'assistant')),
  content text NOT NULL CHECK (char_length(content) BETWEEN 1 AND 20000),
  mode text CHECK (mode IN ('RAG', 'DATA', 'INSUFFICIENT')),
  sources jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(sources) = 'array'),
  suggestions jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(suggestions) = 'array'),
  notice text,
  revision text,
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (conversation_id, citizen_id, tenant_id)
    REFERENCES citizen_ai_conversations (id, citizen_id, tenant_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS citizen_ai_messages_conversation_idx
  ON citizen_ai_messages (conversation_id, id ASC);

-- Neither a direct query nor a crafted conversation id may expose another citizen's history.
ALTER TABLE citizen_ai_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizen_ai_conversations FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS citizen_ai_conversation_owner ON citizen_ai_conversations;
CREATE POLICY citizen_ai_conversation_owner ON citizen_ai_conversations FOR ALL
 USING (citizen_id = nullif(current_setting('app.citizen_id', true), '')::uuid
   AND tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
 WITH CHECK (citizen_id = nullif(current_setting('app.citizen_id', true), '')::uuid
   AND tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);

ALTER TABLE citizen_ai_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizen_ai_messages FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS citizen_ai_message_owner ON citizen_ai_messages;
CREATE POLICY citizen_ai_message_owner ON citizen_ai_messages FOR ALL
 USING (citizen_id = nullif(current_setting('app.citizen_id', true), '')::uuid
   AND tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
 WITH CHECK (citizen_id = nullif(current_setting('app.citizen_id', true), '')::uuid
   AND tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);

DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'communeos_app') THEN
   GRANT SELECT, INSERT, DELETE ON citizen_ai_conversations, citizen_ai_messages TO communeos_app;
   GRANT UPDATE (updated_at, title) ON citizen_ai_conversations TO communeos_app;
   GRANT USAGE, SELECT ON SEQUENCE citizen_ai_messages_id_seq TO communeos_app;
 END IF;
END $$;
