-- PostgreSQL 17: schema for citizen-channel demonstration data only.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS tenants (
  id uuid PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL
);
CREATE TABLE IF NOT EXISTS citizens (
  id uuid PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  login_name text NOT NULL UNIQUE,
  display_name text NOT NULL,
  email text,
  phone text,
  address text,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS procedures (
  id text PRIMARY KEY,
  title text NOT NULL,
  category text NOT NULL,
  summary text NOT NULL,
  icon text NOT NULL DEFAULT 'file-text',
  sla_days integer NOT NULL DEFAULT 3 CHECK (sla_days >= 0),
  fee_note text NOT NULL DEFAULT 'Theo quy định',
  instructions text NOT NULL DEFAULT '',
  published boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS procedure_documents (
  procedure_id text NOT NULL REFERENCES procedures(id) ON DELETE CASCADE,
  document_code text NOT NULL,
  document_name text NOT NULL,
  is_required boolean NOT NULL DEFAULT true,
  PRIMARY KEY(procedure_id, document_code)
);
CREATE SEQUENCE IF NOT EXISTS citizen_case_number START WITH 100500;
CREATE TABLE IF NOT EXISTS applications (
  id text PRIMARY KEY,
  citizen_id uuid NOT NULL REFERENCES citizens(id),
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  procedure_id text NOT NULL REFERENCES procedures(id),
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('draft','submitted','processing','supplement','completed','rejected')),
  applicant_name text NOT NULL,
  applicant_phone text,
  description text NOT NULL DEFAULT '',
  form_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  due_at date,
  result_note text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
-- Existing installations: drafts must not look as if they were already submitted.
ALTER TABLE applications ALTER COLUMN submitted_at DROP NOT NULL;
ALTER TABLE applications ALTER COLUMN submitted_at DROP DEFAULT;
UPDATE applications SET submitted_at=NULL, due_at=NULL WHERE status='draft'
  AND (submitted_at IS NOT NULL OR due_at IS NOT NULL);
CREATE INDEX IF NOT EXISTS applications_citizen_updated_idx ON applications(citizen_id, updated_at DESC);
CREATE TABLE IF NOT EXISTS application_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id text NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  note text NOT NULL,
  actor_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS application_documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  application_id text NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  document_code text NOT NULL,
  original_name text NOT NULL,
  storage_key text NOT NULL UNIQUE,
  mime_type text NOT NULL,
  size_bytes integer NOT NULL CHECK(size_bytes BETWEEN 1 AND 5242880),
  uploaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS citizen_notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  citizen_id uuid NOT NULL REFERENCES citizens(id),
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  application_id text REFERENCES applications(id),
  title text NOT NULL,
  body text NOT NULL,
  category text NOT NULL DEFAULT 'case',
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notification_inbox_idx ON citizen_notifications(citizen_id, created_at DESC);
CREATE TABLE IF NOT EXISTS citizen_feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  citizen_id uuid NOT NULL REFERENCES citizens(id),
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  subject text NOT NULL,
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS citizen_support_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  citizen_id uuid NOT NULL REFERENCES citizens(id),
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  application_id text REFERENCES applications(id),
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS citizen_faq (
  id serial PRIMARY KEY,
  question text NOT NULL,
  answer text NOT NULL,
  keywords text NOT NULL DEFAULT ''
);

