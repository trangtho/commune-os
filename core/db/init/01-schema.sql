-- Authentication uses a restricted SECURITY DEFINER lookup; app cannot enumerate citizen accounts.
CREATE OR REPLACE FUNCTION citizen_login_lookup(p_login text)
RETURNS TABLE(id uuid, tenant_id uuid, display_name text, password_hash text)
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  SELECT c.id, c.tenant_id, c.display_name, c.password_hash
  FROM citizens c WHERE c.login_name = p_login LIMIT 1;
$$;
REVOKE ALL ON FUNCTION citizen_login_lookup(text) FROM PUBLIC;
DO $$ BEGIN
  IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'communeos_app') THEN
    GRANT USAGE ON SCHEMA public TO communeos_app;
    GRANT SELECT ON tenants, procedures, procedure_documents, citizen_faq TO communeos_app;
    GRANT SELECT, UPDATE (display_name, email, phone, address, password_hash) ON citizens TO communeos_app;
    GRANT SELECT, INSERT ON applications, application_events, application_documents,
      citizen_notifications, citizen_feedback, citizen_support_messages TO communeos_app;
    GRANT UPDATE (is_read) ON citizen_notifications TO communeos_app;
    -- Draft editing and final submission update these exact columns.
    -- Restrict row ownership via FORCE RLS; never grant UPDATE on citizen_id or tenant_id.
    GRANT UPDATE (status, updated_at, applicant_name, applicant_phone,
      description, form_data, submitted_at, due_at) ON applications TO communeos_app;
    GRANT EXECUTE ON FUNCTION citizen_login_lookup(text) TO communeos_app;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO communeos_app;
  END IF;
END $$;


-- Real-time invalidation: only a small resource type and owner IDs are notified.
-- PostgreSQL NOTIFY is transactional: listeners only receive committed changes.
-- No names, documents, or personal data are sent over the notification channel.
CREATE OR REPLACE FUNCTION public.communeos_notify_citizen_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_resource text;
  v_citizen uuid;
  v_tenant uuid;
  v_application text;
BEGIN
  IF TG_TABLE_NAME IN ('procedures', 'procedure_documents') THEN
    v_resource := 'procedures';
  ELSIF TG_TABLE_NAME = 'citizens' THEN
    v_resource := 'profile';
    IF TG_OP = 'DELETE' THEN
      v_citizen := OLD.id;
      v_tenant := OLD.tenant_id;
    ELSE
      v_citizen := NEW.id;
      v_tenant := NEW.tenant_id;
    END IF;
  ELSIF TG_TABLE_NAME = 'citizen_notifications' THEN
    v_resource := 'notifications';
    IF TG_OP = 'DELETE' THEN
      v_citizen := OLD.citizen_id;
      v_tenant := OLD.tenant_id;
    ELSE
      v_citizen := NEW.citizen_id;
      v_tenant := NEW.tenant_id;
    END IF;
  ELSIF TG_TABLE_NAME = 'applications' THEN
    v_resource := 'applications';
    IF TG_OP = 'DELETE' THEN
      v_citizen := OLD.citizen_id;
      v_tenant := OLD.tenant_id;
    ELSE
      v_citizen := NEW.citizen_id;
      v_tenant := NEW.tenant_id;
    END IF;
  ELSIF TG_TABLE_NAME IN ('application_events', 'application_documents') THEN
    v_resource := 'applications';
    IF TG_OP = 'DELETE' THEN
      v_application := OLD.application_id;
    ELSE
      v_application := NEW.application_id;
    END IF;
    SELECT citizen_id, tenant_id INTO v_citizen, v_tenant
      FROM public.applications WHERE id = v_application;
    IF v_citizen IS NULL THEN
      IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
      RETURN NEW;
    END IF;
  ELSE
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  PERFORM pg_notify('communeos_citizen_changes', json_build_object(
    'resource', v_resource,
    'citizenId', v_citizen,
    'tenantId', v_tenant
  )::text);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

-- Idempotent: safe to run with `make repair-db` on an existing volume.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'procedures', 'procedure_documents', 'applications',
    'application_events', 'application_documents',
    'citizen_notifications', 'citizens'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS communeos_realtime_changed ON public.%I', t);
    EXECUTE format(
      'CREATE TRIGGER communeos_realtime_changed AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.communeos_notify_citizen_change()',
      t
    );
  END LOOP;
END $$;
