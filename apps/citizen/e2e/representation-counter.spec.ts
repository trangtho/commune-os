import {test,expect,type Page} from '@playwright/test'
async function login(page:Page){
  await page.goto('/dang-nhap')
  await page.getByLabel('Tên đăng nhập').fill(process.env.E2E_USERNAME||'congdan.demo')
  await page.getByLabel('Mật khẩu').fill(process.env.E2E_PASSWORD||'Demo@2026!')
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click()
  await expect(page).not.toHaveURL(/dang-nhap/)
}
test('Guest counter ticket cannot access private records or submit applications',async({page})=>{
  await page.goto('/tai-quay')
  await expect(page.getByRole('heading',{name:'Hỗ trợ thủ tục tại quầy'})).toBeVisible()
  const privateResponse=await page.request.get('/api/representations')
  expect(privateResponse.status()).toBe(401)
  await page.locator('#counter-procedure').selectOption('khai-sinh')
  await page.getByRole('button',{name:/Tạo mã phiên/}).click()
  await expect(page.getByText('Mã phiên chuẩn bị tại quầy')).toBeVisible()
  await expect(page.getByText(/không xác thực danh tính/)).toBeVisible()
  const current=await (await page.request.get('/api/counter/sessions/current')).json()
  expect(current.active).toBe(true)
  expect(current.procedureId).toBe('khai-sinh')
  const resolved=await (await page.request.get(`/api/counter/sessions/${current.code}`)).json()
  expect(resolved).not.toHaveProperty('citizenId')
  expect(resolved.procedureId).toBe('khai-sinh')
  const denied=await page.request.post('/api/applications',{data:{procedureId:'khai-sinh',applicantName:'Test',formData:{}}})
  expect(denied.status()).toBe(401)
  await page.getByRole('button',{name:'Kết thúc và xóa phiên'}).click()
  const expired=await page.request.get(`/api/counter/sessions/${current.code}`)
  expect(expired.status()).toBe(404)
})
test('Representation stays pending; user cannot self-approve through registration',async({page})=>{
  await login(page)
  await page.goto('/dai-dien')
  await expect(page.getByRole('heading',{name:'Đại diện thực hiện thủ tục cho người thân'})).toBeVisible()
  await page.locator('#rep-name').fill('Người thân kiểm thử')
  await page.locator('#rep-procedure').selectOption('khai-sinh')
  const expiry=new Date(Date.now()+7*86400_000).toISOString().slice(0,10)
  await page.locator('#rep-expiry').fill(expiry)
  await page.getByRole('button',{name:'Gửi yêu cầu đại diện'}).click()
  await expect(page.getByText('Người thân kiểm thử').first()).toBeVisible()
  await expect(page.getByText('Chờ xác minh').first()).toBeVisible()
  const list=await (await page.request.get('/api/representations')).json()
  const created=list.items.find((r:{represented_name:string})=>r.represented_name==='Người thân kiểm thử')
  expect(created.status).toBe('pending')
  const fake=await page.request.post('/api/applications',{data:{procedureId:'khai-sinh',applicantName:'Người thân kiểm thử',phone:'',representationId:created.id,formData:{}}})
  expect(fake.status()).toBe(403)
  await page.request.post(`/api/representations/${created.id}/revoke`)
})
