import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read = path => readFileSync(new URL(path,import.meta.url),'utf8')
const migration=read('../../../core/db/init/07-citizen-handoff-support.sql')
const compose=read('../../../docker-compose.yml')
const handoff=read('../server/api/applications/[id]/handoff/index.post.ts')
const redeem=read('../server/api/internal/handoffs/redeem.post.ts')
const staffBridge=read('../server/utils/staff-bridge.ts')
const ticketNew=read('../server/api/tickets/index.post.ts')
const ticketReply=read('../server/api/tickets/[id]/reply.post.ts')
const staffUpdate=read('../server/api/internal/support/tickets/[id]/update.post.ts')
test('handoff code is random, hashed, expires, and can only be issued for an owned draft',()=>{
 assert.match(handoff,/randomBytes\(24\)/)
 assert.match(handoff,/createHash\('sha256'\)/)
 assert.match(handoff,/citizenTx\(event/)
 assert.match(handoff,/row\.status!=='draft'/)
 assert.match(handoff,/15 minutes/)
 assert.match(migration,/code_hash text NOT NULL UNIQUE/)
 assert.match(migration,/redeemed_at IS NOT NULL/)
 assert.match(migration,/FOR UPDATE/)
 assert.match(migration,/h\.tenant_id<>p_tenant/)
 assert.match(redeem,/requireStaffBridge\(event\)/)
 assert.match(redeem,/citizen_staff_redeem_handoff/)
})
test('staff service requires configured strong bearer credential and staff tenant scope',()=>{
 assert.match(staffBridge,/configured\.length<32/)
 assert.match(staffBridge,/timingSafeEqual/)
 assert.match(staffBridge,/x-communeos-tenant-id/)
 assert.match(staffBridge,/x-communeos-staff-id/)
 assert.match(compose,/CITIZEN_STAFF_BRIDGE_TOKEN/)
 assert.match(migration,/citizen_staff_handoff_document/)
 assert.match(read('../server/api/internal/handoffs/[id]/documents/[documentId].get.ts'),/requireStaffBridge/)
 assert.match(migration,/redeemed_at>now\(\)-interval '2 hours'/)
})
test('support tickets have account scoped access, immutable staff status for citizens, and conversation history',()=>{
 assert.match(migration,/citizen_support_tickets FORCE ROW LEVEL SECURITY/)
 assert.match(migration,/citizen_support_ticket_events FORCE ROW LEVEL SECURITY/)
 assert.match(migration,/CREATE POLICY citizen_ticket_owner_create/)
 assert.match(migration,/CREATE POLICY citizen_ticket_event_read/)
 assert.match(ticketNew,/citizenTx\(event/)
 assert.match(ticketNew,/applicationId/)
 assert.match(ticketReply,/citizen_reply_support_ticket/)
 assert.match(migration,/WHEN t.status='waiting_citizen'/)
 assert.match(staffUpdate,/requireStaffBridge/)
 assert.match(staffUpdate,/citizen_staff_update_support_ticket/)
 assert.match(migration,/INSERT INTO citizen_notifications\(citizen_id,tenant_id,category,title,body\)/)
})
test('citizen interface keeps main layout and links cases to handoff and ticket history',()=>{
 const layout=read('../layouts/default.vue')
 assert.match(layout,/\/chuyen-tiep/)
 assert.match(layout,/\/yeu-cau-ho-tro/)
 assert.match(read('../pages/ho-so/[id].vue'),/chuyen-tiep\?case=/)
 assert.match(read('../pages/chuyen-tiep.vue'),/Mã chỉ có hiệu lực 15 phút/)
 assert.match(read('../pages/yeu-cau-ho-tro.vue'),/Yêu cầu của tôi/)
 assert.match(read('../pages/yeu-cau-ho-tro/[id].vue'),/Lịch sử trao đổi/)
})
