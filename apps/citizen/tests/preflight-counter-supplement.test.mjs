import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const root=new URL('../../../',import.meta.url)
const read=(path)=>readFileSync(new URL(path,root),'utf8')
test('Preflight verifies persisted form and required document types at API and submission',()=>{
 const checker=read('apps/citizen/server/utils/preflight.ts')
 assert.match(checker,/validateProcedureForm/)
 assert.match(checker,/procedure_documents[\s\S]*is_required/)
 assert.match(checker,/requireApprovedRepresentation/)
 assert.match(checker,/permittedReceivingTenant/)
 assert.match(checker,/Cần cán bộ kiểm tra/)
 const submit=read('apps/citizen/server/api/applications/[id]/submit.post.ts')
 assert.match(submit,/reviewStoredDraft/)
 const form=read('apps/citizen/pages/nop-ho-so/[slug].vue')
 assert.match(form,/preflight\?\.blocking/)
 assert.match(form,/preflight\?\.verify/)
 assert.match(form,/!preflight\?\.ready/)
})
test('Counter queue allocates tickets atomically and limits cross-tenant access',()=>{
 const sql=read('core/db/init/12-citizen-case-review-counter.sql')
 assert.match(sql,/citizen_book_counter_slot/)
 assert.match(sql,/FOR UPDATE/)
 assert.match(sql,/next_ticket_no=next_ticket_no\+1/)
 assert.match(sql,/s\.tenant_id<>v_tenant/)
 assert.match(sql,/status IN \('booked','checked_in','serving'\)/)
 assert.match(sql,/published AND starts_at>now\(\)/)
 assert.match(sql,/REVOKE ALL ON FUNCTION api\.set_counter_ticket_status/)
 assert.match(sql,/GRANT EXECUTE ON FUNCTION citizen_cancel_counter_booking/)
 const api=read('apps/citizen/server/api/counter/bookings/index.post.ts')
 assert.match(api,/citizen_book_counter_slot/)
 assert.match(read('apps/citizen/pages/lich-hen-mot-cua.vue'),/Đang phục vụ/)
})
test('Citizen-facing stages are derived from authenticated staff updates, not invented workflow deadlines',()=>{
 const stages=read('apps/citizen/server/api/applications/[id]/stages.get.ts')
 assert.match(stages,/citizen_case_stage_updates/)
 const ui=read('apps/citizen/components/CaseTimeline.vue')
 assert.match(ui,/Chỉ hiển thị công đoạn do cán bộ cập nhật/)
 assert.match(ui,/Chưa có thông tin công đoạn chi tiết/)
 assert.match(ui,/stage\.reason/)
})
test('Structured supplement demands specific fresh documents or field responses',()=>{
 const sql=read('core/db/init/12-citizen-case-review-counter.sql')
 assert.match(sql,/api\.request_citizen_case_supplement/)
 assert.match(sql,/citizen_answer_supplement_item/)
 assert.match(sql,/d\.uploaded_at>r\.created_at/)
 assert.match(sql,/a\.form_data \? \(item->>'key'\)/)
 const complete=read('apps/citizen/server/api/applications/[id]/complete-supplement.post.ts')
 assert.match(complete,/requested\.length/)
 assert.match(complete,/item\.kind==='field'/)
 assert.match(complete,/item\.kind==='document'/)
 const ui=read('apps/citizen/pages/ho-so/[id]/bo-sung.vue')
 assert.match(ui,/Cán bộ chưa gửi danh sách chi tiết/)
 assert.match(ui,/eligibleDocs\(item\)/)
})
